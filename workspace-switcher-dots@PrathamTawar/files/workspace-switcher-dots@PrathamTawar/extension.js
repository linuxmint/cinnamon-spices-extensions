class WorkspaceDots {
    constructor(metadata) {
        this.uuid = metadata.uuid;
        this.cssPath = GLib.build_filenamev([GLib.get_user_cache_dir(), this.uuid, "stylesheet.css"]);
        this.styleArg = null;
        this.reloadId = 0;
        this.themeSettings = null;
        this.themeSignal = 0;

        this.mode = "light";
        this.customInactive = PRESETS.light.inactive;
        this.customHover = PRESETS.light.hover;
        this.customActive = PRESETS.light.active;

        this.settings = new Settings.ExtensionSettings(this, this.uuid);
        let onChange = () => this.apply();
        this.settings.bind("mode", "mode", onChange);
        this.settings.bind("custom-inactive", "customInactive", onChange);
        this.settings.bind("custom-hover", "customHover", onChange);
        this.settings.bind("custom-active", "customActive", onChange);

        // A theme change replaces the St theme, which drops our stylesheet
        try {
            this.themeSettings = new Gio.Settings({ schema_id: "org.cinnamon.theme" });
            this.themeSignal = this.themeSettings.connect("changed::name", () => this.queueApply(1000));
        } catch (e) {
            global.logError(this.uuid + ": " + e);
        }

        this.apply();
    }

    colors() {
        if (this.mode === "custom-colors") {
            return {
                inactive: safeColor(this.customInactive, PRESETS.light.inactive),
                hover: safeColor(this.customHover, PRESETS.light.hover),
                active: safeColor(this.customActive, PRESETS.light.active)
            };
        }
        return PRESETS[this.mode] || PRESETS.light;
    }

    theme() {
        return St.ThemeContext.get_for_stage(global.stage).get_theme();
    }

    unloadStyle() {
        let theme = this.theme();
        let variants = [this.cssPath, Gio.File.new_for_path(this.cssPath)];
        for (let arg of variants) {
            try {
                theme.unload_stylesheet(arg);
            } catch (e) {
                // not loaded with this argument type
            }
        }
        this.styleArg = null;
    }

    loadStyle() {
        let theme = this.theme();
        let variants = [this.cssPath, Gio.File.new_for_path(this.cssPath)];
        let lastError = null;
        for (let arg of variants) {
            try {
                theme.load_stylesheet(arg);
                this.styleArg = arg;
                return;
            } catch (e) {
                lastError = e;
            }
        }
        throw lastError;
    }

    apply() {
        try {
            writeFile(this.cssPath, buildCss(this.colors()));
            this.unloadStyle();
            this.loadStyle();
        } catch (e) {
            global.logError(this.uuid + ": " + e);
        }
    }

    queueApply(delay) {
        if (this.reloadId)
            Mainloop.source_remove(this.reloadId);
        this.reloadId = Mainloop.timeout_add(delay, () => {
            this.reloadId = 0;
            this.apply();
            return false;
        });
    }

    destroy() {
        if (this.reloadId) {
            Mainloop.source_remove(this.reloadId);
            this.reloadId = 0;
        }
        if (this.themeSettings && this.themeSignal) {
            this.themeSettings.disconnect(this.themeSignal);
            this.themeSignal = 0;
        }
        try {
            this.unloadStyle();
        } catch (e) {
            global.logError(this.uuid + ": " + e);
        }
        try {
            this.settings.finalize();
        } catch (e) {
            global.logError(this.uuid + ": " + e);
        }
    }
}

function init(metadata) {
    meta = metadata;
}

function enable() {
    dots = new WorkspaceDots(meta);
}

function disable() {
    if (dots) {
        dots.destroy();
        dots = null;
    }
}
