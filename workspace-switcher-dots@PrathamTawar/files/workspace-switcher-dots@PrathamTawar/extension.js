// Workspace Dots
// Small dots for the Workspace Switcher (Simple buttons mode), with a wider
// bar for the active workspace. The stylesheet is generated from the extension
// settings and loaded into the current theme, so it works with any theme.

const Gio = imports.gi.Gio;
const GLib = imports.gi.GLib;
const St = imports.gi.St;
const Mainloop = imports.mainloop;
const Settings = imports.ui.settings;

const PRESETS = {
    light: { inactive: "rgba(254, 254, 254, 1)", hover: "#727fff", active: "#3f51ff" },
    dark:  { inactive: "rgba(45, 45, 45, 0.80)",    hover: "#727fff", active: "#3f51ff" }
};

let meta = null;
let dots = null;

// Only plain CSS colors are accepted, so a setting can never inject other CSS.
function safeColor(value, fallback) {
    if (typeof value !== "string")
        return fallback;
    let v = value.trim();
    if (/^#[0-9a-fA-F]{3,8}$/.test(v))
        return v;
    if (/^rgba?\(\s*[0-9.]+%?\s*(,\s*[0-9.]+%?\s*){2,3}\)$/.test(v))
        return v;
    return fallback;
}

function writeFile(path, text) {
    GLib.mkdir_with_parents(GLib.path_get_dirname(path), 0o755);
    let data = (typeof TextEncoder !== "undefined") ? new TextEncoder().encode(text) : text;
    GLib.file_set_contents(path, data);
}

